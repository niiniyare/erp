// Package migration generates golang-migrate compatible SQL migration files
// from registered EntityDefinitions.
//
// Generated migration pair per entity:
//
//	NNNNNN_entity_{name}.up.sql   — CREATE TABLE + RLS + indexes + GRANTs
//	NNNNNN_entity_{name}.down.sql — DROP TABLE (+ DROP POLICY cascade)
//
// RLS pattern (matches existing codebase):
//   - application_role : tenant_isolation_policy (fail-closed, no IS NOT NULL guard)
//   - admin_role       : admin_full_access_policy USING(TRUE)
//   - readonly_role    : SELECT-only, non-deleted rows
//
// Caller is responsible for writing the returned strings to files.
package migration

import (
	"fmt"
	"strings"
	"time"

	"awo.so/framework/definition"
	platformorg "awo.so/framework/platform/org"
)

// File is one half of a migration pair.
type File struct {
	Name    string // e.g. "001200_entity_sales_order.up.sql"
	Content string
}

// GenerateEntity produces an up+down migration pair for def.
// seq is the 6-digit migration sequence number (e.g. 1200).
func GenerateEntity(def *definition.EntityDefinition, seq int) (up, down File) {
	name := fmt.Sprintf("%06d_entity_%s", seq, def.Name)

	up = File{
		Name:    name + ".up.sql",
		Content: generateUp(def, seq),
	}
	down = File{
		Name:    name + ".down.sql",
		Content: generateDown(def),
	}
	return
}

// GenerateAll produces migration pairs for all registered EntityDefinitions,
// starting at startSeq and incrementing by 1 per entity.
func GenerateAll(startSeq int) []File {
	defs := definition.All()
	files := make([]File, 0, len(defs)*2)
	for i, def := range defs {
		up, down := GenerateEntity(def, startSeq+i)
		files = append(files, up, down)
	}
	return files
}

// ──────────────────────────────────────────────────────────────────
// Up migration
// ──────────────────────────────────────────────────────────────────

func generateUp(def *definition.EntityDefinition, seq int) string {
	var b strings.Builder

	header(&b, def, seq)
	createTable(&b, def)
	indexes(&b, def)
	rls(&b, def)
	grants(&b, def)

	return b.String()
}

func header(b *strings.Builder, def *definition.EntityDefinition, seq int) {
	desc := def.Description
	if desc == "" {
		desc = def.Label + " entity table — generated by awo.so/framework/migration."
	}
	fmt.Fprintf(
		b, `-- --------------------------------------------------------------------
-- %06d  %s
-- --------------------------------------------------------------------
-- %s
--
-- Generated: %s
-- Entity:    %s  (module: %s)
-- Table:     %s
-- OrgScope:  %s  SoftDelete: %v  Audited: %v
-- --------------------------------------------------------------------

`,
		seq, def.TableName(),
		desc,
		time.Now().UTC().Format("2006-01-02"),
		def.Name, def.Module,
		def.TableName(),
		effectiveScope(def), def.SoftDelete, def.Audited,
	)
}

func createTable(b *strings.Builder, def *definition.EntityDefinition) {
	fmt.Fprintf(b, "CREATE TABLE IF NOT EXISTS %s (\n", def.TableName())

	// System columns first.
	fmt.Fprintf(b, "  id         UUID        NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,\n")

	if !def.IsGlobal() {
		fmt.Fprintf(b, "  tenant_id  UUID        NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,\n")
	}
	if def.IsUnitScoped() {
		// org_unit_id scopes the record to a node in the org_units tree.
		// Access control is tree-based: viewer's unit must be an ancestor-or-equal
		// of this unit. RLS enforces tenant isolation; org-scope is enforced in
		// the query layer (WHERE org_unit_id = ANY(subtree_descendants)).
		fmt.Fprintf(b, "  org_unit_id UUID       NOT NULL REFERENCES org_units(uuid) ON DELETE RESTRICT,\n")
	}

	// Custom fields.
	for _, f := range def.Fields {
		colDef := fieldToColumn(f)
		fmt.Fprintf(b, "  %s,\n", colDef)
	}

	// Audit timestamps.
	fmt.Fprintf(b, "  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),\n")
	fmt.Fprintf(b, "  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()")

	if def.SoftDelete {
		fmt.Fprintf(b, ",\n  deleted_at TIMESTAMPTZ")
	}

	// Custom fields JSONB column.
	fmt.Fprintf(b, ",\n  custom_fields JSONB NOT NULL DEFAULT '{}'")

	fmt.Fprintf(b, "\n);\n\n")

	// Table comment.
	label := def.Label
	if label == "" {
		label = def.Name
	}
	fmt.Fprintf(b, "COMMENT ON TABLE %s IS '%s — module: %s';\n\n",
		def.TableName(), label, def.Module)
}

func fieldToColumn(f *definition.FieldDef) string {
	col := pgIdent(f.Name)
	colType := fieldTypeToPG(f)

	parts := []string{col, colType}

	if f.IsRequired {
		parts = append(parts, "NOT NULL")
	}

	if f.DefaultVal != nil {
		parts = append(parts, fmt.Sprintf("DEFAULT %s", pgLiteral(f.DefaultVal)))
	}

	if f.MaxLength > 0 {
		// Already encoded in type for VARCHAR; skip separate constraint.
	}

	if f.IsUnique {
		parts = append(parts, "UNIQUE")
	}

	// Emit FK reference for Link fields that declare a LinkedEntity.
	// DynamicLink has no FK constraint (polymorphic, app-layer integrity only).
	if f.Type == definition.FieldTypeLink && f.LinkedEntity != "" {
		target := definition.Lookup(f.LinkedEntity)
		if target != nil {
			parts = append(parts, fmt.Sprintf("REFERENCES %s(id) ON DELETE RESTRICT", target.TableName()))
		}
	}

	return strings.Join(parts, " ")
}

func fieldTypeToPG(f *definition.FieldDef) string {
	switch f.Type {
	case definition.FieldTypeData, definition.FieldTypeSmallText:
		if f.MaxLength > 0 {
			return fmt.Sprintf("VARCHAR(%d)", f.MaxLength)
		}
		return "VARCHAR(255)"
	case definition.FieldTypeLongText:
		return "TEXT"
	case definition.FieldTypeInt:
		return "BIGINT"
	case definition.FieldTypeFloat:
		return "DOUBLE PRECISION"
	case definition.FieldTypeCurrency:
		// Stored as NUMERIC(20,4) — never FLOAT (precision loss). Docs §5.1.1.
		return "NUMERIC(20,4)"
	case definition.FieldTypeBool:
		return "BOOLEAN"
	case definition.FieldTypeDate:
		return "DATE"
	case definition.FieldTypeDateTime:
		return "TIMESTAMPTZ"
	case definition.FieldTypeTime:
		return "TIME"
	case definition.FieldTypeUUID:
		return "UUID"
	case definition.FieldTypeSelect:
		return "VARCHAR(100)" // stable key values; doc §5.1.2 Select
	case definition.FieldTypeMultiSelect:
		return "TEXT[]" // array of stable keys; doc §5.1.2 MultiSelect
	case definition.FieldTypeJSON:
		return "JSONB"
	case definition.FieldTypeLink, definition.FieldTypeDynamicLink:
		return "UUID"
	case definition.FieldTypeTable, definition.FieldTypeAttach, definition.FieldTypeAttachImage:
		return "JSONB"
	default:
		return "TEXT"
	}
}

func pgLiteral(v any) string {
	switch val := v.(type) {
	case string:
		// Escape single quotes.
		return "'" + strings.ReplaceAll(val, "'", "''") + "'"
	case bool:
		if val {
			return "TRUE"
		}
		return "FALSE"
	case int, int64, float64:
		return fmt.Sprintf("%v", val)
	default:
		return fmt.Sprintf("'%v'", val)
	}
}

// ──────────────────────────────────────────────────────────────────
// Indexes
// ──────────────────────────────────────────────────────────────────

func indexes(b *strings.Builder, def *definition.EntityDefinition) {
	table := def.TableName()

	// tenant_id index (most common join column).
	if !def.IsGlobal() {
		fmt.Fprintf(b, "CREATE INDEX IF NOT EXISTS %s_tenant_id_idx ON %s (tenant_id);\n",
			table, table)
	}

	// org_unit_id index — subtree list queries use WHERE org_unit_id = ANY($n).
	if def.IsUnitScoped() {
		fmt.Fprintf(b, "CREATE INDEX IF NOT EXISTS %s_org_unit_id_idx ON %s (org_unit_id);\n",
			table, table)
		// Composite index for the common tenant + unit filter pattern.
		fmt.Fprintf(b, "CREATE INDEX IF NOT EXISTS %s_tenant_org_unit_idx ON %s (tenant_id, org_unit_id);\n",
			table, table)
	}

	// soft-delete index (WHERE deleted_at IS NULL is on every list query).
	if def.SoftDelete {
		fmt.Fprintf(b, "CREATE INDEX IF NOT EXISTS %s_active_idx ON %s (tenant_id) WHERE deleted_at IS NULL;\n",
			table, table)
	}

	for _, f := range def.Fields {
		// GIN trgm index for pg_trgm full-text search.
		if f.IsSearchable {
			fmt.Fprintf(b,
				"CREATE INDEX IF NOT EXISTS %s_%s_trgm_idx ON %s USING GIN (%s gin_trgm_ops);\n",
				table, f.Name, table, pgIdent(f.Name))
		}

		// B-tree index on FK columns (Link / DynamicLink).
		if (f.Type == definition.FieldTypeLink || f.Type == definition.FieldTypeDynamicLink) && !f.IsUnique {
			fmt.Fprintf(b,
				"CREATE INDEX IF NOT EXISTS %s_%s_idx ON %s (%s);\n",
				table, f.Name, table, pgIdent(f.Name))
		}
	}

	b.WriteString("\n")
}

// ──────────────────────────────────────────────────────────────────
// RLS — matches codebase pattern exactly
// ──────────────────────────────────────────────────────────────────

func rls(b *strings.Builder, def *definition.EntityDefinition) {
	if def.IsGlobal() {
		// Global tables: no tenant scoping but still lock down with role policies.
		fmt.Fprintf(b, "ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", def.TableName())
		fmt.Fprintf(b, "ALTER TABLE %s FORCE  ROW LEVEL SECURITY;\n\n", def.TableName())

		fmt.Fprintf(b,
			"CREATE POLICY admin_full_access_policy ON %s FOR ALL TO admin_role USING (TRUE) WITH CHECK (TRUE);\n",
			def.TableName())
		fmt.Fprintf(b,
			"CREATE POLICY app_read_policy ON %s FOR SELECT TO application_role USING (TRUE);\n",
			def.TableName())
		fmt.Fprintf(b,
			"CREATE POLICY readonly_policy ON %s FOR SELECT TO readonly_role USING (TRUE);\n\n",
			def.TableName())
		return
	}

	table := def.TableName()

	fmt.Fprintf(b, "ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", table)
	fmt.Fprintf(b, "ALTER TABLE %s FORCE  ROW LEVEL SECURITY;\n\n", table)

	softDeleteClause := ""
	if def.SoftDelete {
		softDeleteClause = "\n    AND deleted_at IS NULL"
	}

	// application_role — fail-closed tenant isolation.
	fmt.Fprintf(b, `CREATE POLICY tenant_isolation_policy ON %s
  FOR ALL TO application_role
  USING  (tenant_id = current_tenant_id()%s)
  WITH CHECK (tenant_id = current_tenant_id()%s);

`,
		table, softDeleteClause, softDeleteClause)

	// admin_role — unrestricted (auditable via pg_policies).
	fmt.Fprintf(b, `CREATE POLICY admin_full_access_policy ON %s
  FOR ALL TO admin_role
  USING (TRUE) WITH CHECK (TRUE);

`, table)

	// readonly_role — SELECT on active rows only.
	readonlyFilter := "tenant_id = current_tenant_id()"
	if def.SoftDelete {
		readonlyFilter += " AND deleted_at IS NULL"
	}
	fmt.Fprintf(b, `CREATE POLICY readonly_policy ON %s
  FOR SELECT TO readonly_role
  USING (%s);

`, table, readonlyFilter)
}

// ──────────────────────────────────────────────────────────────────
// GRANTs
// ──────────────────────────────────────────────────────────────────

func grants(b *strings.Builder, def *definition.EntityDefinition) {
	table := def.TableName()
	fmt.Fprintf(b,
		"GRANT SELECT, INSERT, UPDATE, DELETE ON %s TO application_role, admin_role;\n",
		table)
	fmt.Fprintf(b,
		"GRANT SELECT ON %s TO readonly_role;\n\n",
		table)
}

// ──────────────────────────────────────────────────────────────────
// Down migration
// ──────────────────────────────────────────────────────────────────

func generateDown(def *definition.EntityDefinition) string {
	return fmt.Sprintf(
		"-- Drop RLS policies (cascade with table drop).\nDROP TABLE IF EXISTS %s;\n",
		def.TableName(),
	)
}

// ──────────────────────────────────────────────────────────────────
// Helpers
// ──────────────────────────────────────────────────────────────────

// effectiveScope returns the human-readable OrgScope for the migration header comment.
func effectiveScope(def *definition.EntityDefinition) platformorg.ScopeLevel {
	if def.OrgScope == "" {
		return platformorg.ScopeLevelTenant
	}
	return def.OrgScope
}

// pgIdent returns the column name. Panics on unsafe identifiers (same guard as sqlbuilder).
func pgIdent(name string) string {
	for _, c := range name {
		if !((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_') {
			panic(fmt.Sprintf("migration: unsafe identifier %q", name))
		}
	}
	return name
}
