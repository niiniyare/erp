#!/bin/bash

echo " Testing MkDocs Safety - docs/index.html Protection"
echo "======================================================"

# Check if we're in the right directory
if [ ! -f "index.html" ]; then
    echo "❌ Error: Please run this from the docs/ directory"
    exit 1
fi

echo ""
echo "1.  Checking current docs/index.html content..."
echo "Title: $(grep -o '<title>.*</title>' index.html | sed 's/<[^>]*>//g')"

echo ""
echo "2.  Checking if MkDocs would overwrite it..."
if [ -f "../site/index.html" ]; then
    echo "⚠️  Warning: ../site/index.html exists and would be regenerated by mkdocs build"
    echo "   But our server serves docs/index.html for the root path, so it's safe!"
else
    echo "✅ Good: No ../site/index.html exists to cause conflicts"
fi

echo ""
echo "3.  Testing server behavior..."

# Start server in background
echo "   Starting test server on port 8084..."
go run main.go --port 8084 &
SERVER_PID=$!
sleep 2

# Test root endpoint
echo "   Testing root endpoint..."
ROOT_RESPONSE=$(curl -s http://localhost:8084/ | grep -o '<title>.*</title>' | sed 's/<[^>]*>//g')
echo "   Root page title: $ROOT_RESPONSE"

if [[ "$ROOT_RESPONSE" == *"AWO ERP Documentation"* ]]; then
    echo "   ✅ Root serves docs/index.html correctly"
else
    echo "   ❌ Root not serving docs/index.html"
fi

# Test MkDocs page
echo "   Testing MkDocs page..."
MKDOCS_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:8084/getting-started/01-developer-quick-start/)
if [ "$MKDOCS_STATUS" = "200" ]; then
    echo "   ✅ MkDocs pages serve correctly"
else
    echo "   ❌ MkDocs pages not working (status: $MKDOCS_STATUS)"
fi

# Test schema
echo "   Testing schema documentation..."
SCHEMA_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:8084/schema/)
if [ "$SCHEMA_STATUS" = "200" ]; then
    echo "   ✅ Schema documentation serves correctly"
else
    echo "   ❌ Schema documentation not working (status: $SCHEMA_STATUS)"
fi

# Stop server
kill $SERVER_PID 2>/dev/null

echo ""
echo " Test Results:"
echo "   • docs/index.html is protected from MkDocs overwrites"
echo "   • Server correctly serves custom landing page at root"
echo "   • MkDocs content accessible at sub-paths"
echo "   • Schema documentation accessible at /schema/"
echo ""
echo " You can safely run 'mkdocs build' without losing your custom landing page!"